import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { Readable } from 'node:stream';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createServer } from 'vite';
import { publishingFixture, fakeCleanScanner, imageBytes } from '../../backend/tests/publishing-fixture.js';

const database = process.env.KITSS_CATEGORY_TEST_DB;
test('category CMS: protected publishing, media references and admin/public browser workflow', { skip: !database ? 'No fresh isolated category test database' : false, timeout: 300000 }, async t => {
  const f = await publishingFixture(database, { scanner: fakeCleanScanner });
  let server, vite, browser;
  t.after(async () => { await browser?.close(); await vite?.close(); if (server) await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); await f.close(); });
  const admin = await f.fixtureUser(), reader = await f.fixtureUser(['admin'], ['content.read']);
  const image = await f.media.upload({ purpose: 'cms', stream: Readable.from(await imageBytes()), mime: 'image/png', originalName: 'synthetic-category.png', idempotencyKey: randomUUID(), auth: admin.auth, ctx: f.ctx });
  const { defaultCategoryCards } = await import('../src/modules/user/pages/categories/categoryCards.js');
  let record = await f.publishing.create('pages', { key: 'categories', sections: [{ key: 'legacy', type: 'text', items: [{ heading: 'Legacy coaching', body: 'Old copy', linkKey: 'coaching' }] }] }, admin.auth, f.ctx);
  record = await f.publishing.publish('pages', record.id, { publish: true, expectedRevision: record.revision }, admin.auth, f.ctx);
  server = http.createServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  vite = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { host: '127.0.0.1', port: 0, hmr: false, watch: null, proxy: { '/api': { target: 'http://127.0.0.1:' + server.address().port, changeOrigin: true } } }, logLevel: 'error' });
  await vite.listen(); const base = 'http://127.0.0.1:' + vite.httpServer.address().port;
  f.config.corsOrigins = [base]; f.config.appPublicUrl = base; server.on('request', f.app());
  const csrfResponse = await fetch(base + '/api/v1/auth/csrf');
  const csrfCookie = csrfResponse.headers.getSetCookie()[0].split(';')[0], csrf = (await csrfResponse.json()).data.csrfToken;
  const write = (suffix, data, actor = admin, useCsrf = true, method = 'PATCH') => fetch(base + '/api/v1/admin/content/pages/' + record.id + suffix, { method, headers: { Origin: base, Cookie: [useCsrf ? csrfCookie : '', actor ? 'kitss_staff_session=' + actor.token : ''].filter(Boolean).join('; '), ...(useCsrf ? { 'X-CSRF-Token': csrf } : {}), 'Content-Type': 'application/json' }, body: JSON.stringify(data) });
  await t.test('auth, permissions, CSRF, stale revision and non-category isolation', async () => {
    const data = { expectedRevision: record.revision, categoryCards: defaultCategoryCards };
    assert.equal((await write('', data, null)).status, 401);
    assert.equal((await write('', data, reader)).status, 403);
    assert.equal((await write('', data, admin, false)).status, 403);
    assert.equal((await write('', { ...data, expectedRevision: record.revision + 1 })).status, 409);
    assert.equal((await write('/publish', { publish: true, expectedRevision: record.revision }, reader, true, 'POST')).status, 403);
    const home = await f.publishing.create('pages', { key: 'home' }, admin.auth, f.ctx);
    await assert.rejects(f.publishing.edit('pages', home.id, { expectedRevision: home.revision, categoryCards: [] }, admin.auth, f.ctx), e => e.status === 422);
    const wrongPurpose = await f.media.upload({ purpose: 'banner', stream: Readable.from(await imageBytes()), mime: 'image/png', originalName: 'wrong-purpose.png', idempotencyKey: randomUUID(), auth: admin.auth, ctx: f.ctx });
    await assert.rejects(f.publishing.edit('pages', record.id, { ...data, categoryCards: [{ ...defaultCategoryCards[0], imageAssetId: wrongPurpose.id }] }, admin.auth, f.ctx), e => e.status === 422);
  });
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  await context.addCookies([{ name: 'kitss_staff_session', value: admin.token, url: base, httpOnly: true, sameSite: 'Lax' }]);
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  const page = await context.newPage(); page.setDefaultTimeout(30000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const openManager = async () => { await page.goto(base + '/admin/content', { waitUntil: 'domcontentloaded', timeout: 120000 }); await page.getByRole('button', { name: 'Categories', exact: true }).click(); await page.getByRole('button', { name: 'Add category', exact: true }).waitFor(); await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Add category')?.disabled); };
  const save = async () => { await page.getByRole('button', { name: 'Save categories draft', exact: true }).click(); await page.getByText('Draft saved. Publish when ready to update the Categories page.', { exact: true }).waitFor(); };
  await t.test('admin edits, draft/publish, sixth card, image, filtering, mobile, hiding, reordering and removal', async () => {
    await page.goto(base + '/categories', { waitUntil: 'domcontentloaded', timeout: 120000 });
    await page.getByRole('heading', { name: 'Legacy coaching', level: 2, exact: true }).waitFor();
    await openManager();
    await page.getByRole('button', { name: 'Add category', exact: true }).click();
    const editor = page.getByRole('form', { name: 'Category editor' });
    await editor.getByLabel('Card title', { exact: true }).fill('Extra resources');
    await editor.getByLabel('Description', { exact: true }).fill('Helpful learning material');
    await editor.getByLabel('Filter tab label', { exact: true }).fill('Resources');
    await editor.getByLabel('Badge (optional)', { exact: true }).fill('NEW');
    await editor.getByLabel('Colour', { exact: true }).selectOption('purple');
    await editor.getByLabel('Icon', { exact: true }).selectOption('Library');
    await editor.getByLabel('Destination', { exact: true }).selectOption('/about');
    await editor.getByLabel('Category image', { exact: true }).selectOption(image.id);
    await page.screenshot({ path: fileURLToPath(new URL('../../.runtime/category-admin.png', import.meta.url)), fullPage: true });
    await save();
    assert.equal((await f.publishing.publicPage('categories')).categoryCards, undefined);
    await page.getByRole('button', { name: 'Unpublish categories', exact: true }).waitFor();

    // The manager always offers publication of saved changes separately from unpublishing.
    await page.getByRole('button', { name: 'Publish categories', exact: true }).click();
    await page.getByText('Categories published.', { exact: true }).waitFor();
    await page.goto(base + '/categories', { waitUntil: 'domcontentloaded' });
    const card = page.getByRole('link').filter({ has: page.getByRole('heading', { name: 'Extra resources', exact: true }) });
    await card.waitFor(); assert.equal(await card.getAttribute('href'), '/about');
    await card.locator('img').evaluate(img => img.decode()); assert.equal(await card.locator('img').evaluate(img => img.naturalWidth), 40);
    await page.getByRole('button', { name: 'Resources', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('a.group h2').length === 1);
    assert.equal(await page.getByRole('link').filter({ has: page.getByRole('heading', { level: 2 }) }).count(), 1);
    await page.getByPlaceholder('Search categories', { exact: false }).fill('nomatch');
    await page.getByRole('button', { name: 'Reset Filters', exact: true }).click();
    for (const width of [390, 320]) { await page.setViewportSize({ width, height: 844 }); assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)); }
    await page.screenshot({ path: fileURLToPath(new URL('../../.runtime/category-public-mobile.png', import.meta.url)), fullPage: true });
    assert.equal((await fetch(base + '/api/v1/media/' + image.id + '/content')).status, 200);
    await assert.rejects(f.media.remove(image.id, { expectedRevision: image.revision }, f.ctx), e => e.status === 409);

    await openManager();
    await page.getByRole('button', { name: 'Extra resources', exact: true }).click();
    await page.getByLabel('Hide this card and its filter tab', { exact: true }).check();
    await page.getByRole('button', { name: 'Move Extra resources up', exact: true }).click();
    await save(); await page.getByRole('button', { name: 'Publish categories', exact: true }).click(); await page.getByText('Categories published.', { exact: true }).waitFor();
    await page.goto(base + '/categories', { waitUntil: 'domcontentloaded' });
    await page.getByRole('heading', { name: 'Legacy coaching', level: 2, exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Resources', exact: true }).count(), 0);
    await openManager();
    const item = page.locator('div.border.rounded-xl').filter({ has: page.getByRole('button', { name: 'Extra resources (hidden)', exact: true }) });
    page.once('dialog', dialog => dialog.accept()); await item.getByRole('button', { name: 'Remove', exact: true }).click();
    await save(); await page.getByRole('button', { name: 'Publish categories', exact: true }).click(); await page.getByText('Categories published.', { exact: true }).waitFor();
    const publicPage = await f.publishing.publicPage('categories');
    assert.equal(publicPage.categoryCards.length, 5); assert.equal(publicPage.sections[0].key, 'legacy');
    assert.ok(await f.models.MediaAsset.findById(image.id));
    record = await f.publishing.detail('pages', record.id, true);
    record = await f.publishing.edit('pages', record.id, { expectedRevision: record.revision, categoryCards: [] }, admin.auth, f.ctx);
    record = await f.publishing.publish('pages', record.id, { expectedRevision: record.revision, publish: true }, admin.auth, f.ctx);
    await page.goto(base + '/categories', { waitUntil: 'domcontentloaded' });
    await page.getByText('No category tabs found matching', { exact: false }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Digital Books', exact: true }).count(), 0);
    assert.deepEqual(errors, []);
  });
});

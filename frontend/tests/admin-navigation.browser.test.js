import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createServer } from 'vite';

const executablePath = process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
test('grouped admin sidebar and mobile drawer (mocked HTTP)', { skip: !existsSync(executablePath), timeout: 240000 }, async t => {
  const server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { host: '127.0.0.1', port: 0, hmr: false, watch: null }, logLevel: 'error' });
  await server.listen();
  const browser = await chromium.launch({ executablePath, headless: true });
  t.after(async () => { await browser.close(); await server.close(); });
  const page = await browser.newPage({ viewport: { width: 1440, height: 800 } });
  const base = `http://127.0.0.1:${server.httpServer.address().port}`;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let permissions = ['dashboard.read', 'books.read', 'coaching.read', 'learning.read', 'results.read', 'content.read', 'institutions.read', 'admissions.read', 'registrations.read', 'franchises.read', 'commerce.read', 'refunds.read', 'access.read', 'media.read', 'notifications.read', 'accounts.read', 'accounts.roles.manage', 'settings.read', 'audit.read', 'operations.read'];
  await page.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin !== base) return route.abort();
    if (!url.pathname.startsWith('/api/')) return route.continue();
    if (url.pathname === '/api/v1/auth/me') return route.fulfill({ json: { data: { user: { id: 'NAV-TEST', name: 'Navigation Test Staff', roles: ['admin'], permissions, status: 'active' } } } });
    if (url.pathname === '/api/v1/me/notifications') return route.fulfill({ json: { data: [], meta: { page: 1, totalPages: 1, total: 0, unreadCount: 0 } } });
    return route.fulfill({ status: 404, json: { error: { code: 'FIXTURE', message: 'No business data in this navigation test' } } });
  });
  const goto = path => page.goto(base + path, { waitUntil: 'domcontentloaded', timeout: 120000 });
  await goto('/admin/universities');
  const nav = page.getByRole('navigation', { name: 'Admin sections', exact: true });
  await nav.waitFor();
  await t.test('all 22 routes grouped; active group opens; keyboard toggles groups', async () => {
    assert.equal(await nav.locator('a').count(), 22);
    assert.equal(await nav.getByRole('button').count(), 6);
    assert.equal(await nav.getByRole('button', { name: 'Institutions & admissions' }).getAttribute('aria-expanded'), 'true');
    assert.equal(await nav.getByRole('link', { name: 'Universities', exact: true }).getAttribute('aria-current'), 'page');
    const learning = nav.getByRole('button', { name: 'Learning & results' });
    await learning.focus(); await page.keyboard.press('Enter');
    await nav.getByRole('link', { name: 'Digital Books', exact: true }).waitFor();
    await page.keyboard.press('Space');
    assert.equal(await learning.getAttribute('aria-expanded'), 'false');
    const aside = page.getByRole('complementary', { name: 'Admin sidebar' });
    const before = await aside.boundingBox();
    await page.locator('#admin-main').evaluate(main => { const spacer = document.createElement('div'); spacer.style.height = '2500px'; main.append(spacer); main.scrollTop = 900; });
    assert.ok(await page.locator('#admin-main').evaluate(main => main.scrollTop > 0));
    assert.equal((await aside.boundingBox()).y, before.y);
    const axe = readFileSync(fileURLToPath(new URL('../node_modules/axe-core/axe.min.js', import.meta.url)), 'utf8');
    await page.evaluate(axe);
    assert.deepEqual(await page.evaluate(async () => (await axe.run('nav[aria-label="Admin sections"]', { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } })).violations.map(v => v.id)), []);
  });
  await t.test('desktop sidebar collapses and expands without losing group state', async () => {
    const aside = page.getByRole('complementary', { name: 'Admin sidebar' });
    const main = page.locator('#admin-main');
    const original = await main.boundingBox();
    const expanded = await nav.getByRole('button', { name: 'Institutions & admissions' }).getAttribute('aria-expanded');
    const collapse = page.getByRole('button', { name: 'Collapse admin sidebar', exact: true });
    await collapse.focus(); await page.keyboard.press('Enter');
    await aside.waitFor({ state: 'hidden' });
    const wider = await main.boundingBox();
    assert.ok(wider.width > original.width);
    assert.equal(wider.x, 0);
    const expand = page.getByRole('button', { name: 'Expand admin sidebar', exact: true });
    assert.equal(await expand.getAttribute('aria-expanded'), 'false');
    assert.equal(await expand.evaluate(node => node === document.activeElement), true);
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
    await page.keyboard.press('Space');
    await aside.waitFor();
    assert.equal((await main.boundingBox()).width, original.width);
    assert.equal(await nav.getByRole('button', { name: 'Institutions & admissions' }).getAttribute('aria-expanded'), expanded);
    assert.equal(await collapse.getAttribute('aria-expanded'), 'true');
  });
  await t.test('mobile groups, focus trap, Escape, navigation close and resize recovery', async () => {
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 700 });
      const menu = page.getByRole('button', { name: 'Open admin navigation', exact: true });
      await menu.click();
      const dialog = page.getByRole('dialog', { name: 'Admin navigation', exact: true });
      await dialog.waitFor();
      const mobile = dialog.getByRole('navigation');
      await mobile.getByRole('button', { name: 'Learning & results' }).click();
      await mobile.getByRole('link', { name: 'Digital Books', exact: true }).waitFor();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await dialog.getByRole('link', { name: 'Return to Student App' }).focus();
      await page.keyboard.press('Tab');
      assert.equal(await dialog.evaluate(node => node.contains(document.activeElement)), true);
      await page.keyboard.press('Escape');
      await dialog.waitFor({ state: 'detached' });
      assert.equal(await menu.evaluate(node => node === document.activeElement), true);
      await menu.click();
      await page.getByRole('dialog').getByRole('link', { name: 'Colleges / Institutes', exact: true }).click();
      await page.waitForURL('**/admin/colleges');
      await page.getByRole('dialog').waitFor({ state: 'detached' });
      await page.waitForFunction(() => document.querySelector('#admin-main')?.scrollTop === 0);
      assert.equal(await page.locator('#admin-main').evaluate(main => main.scrollTop), 0);
      await menu.click();
      await page.setViewportSize({ width: 1024, height: 800 });
      await page.getByRole('dialog').waitFor({ state: 'detached' });
      assert.equal(await page.locator('#admin-main').evaluate(main => main.inert), false);
      await goto('/admin/universities');
    }
  });
  await t.test('permission filtering removes unauthorized links and empty groups', async () => {
    await page.setViewportSize({ width: 1440, height: 800 });
    permissions = ['institutions.read'];
    await goto('/admin/universities');
    await nav.waitFor();
    assert.equal(await nav.locator('a').count(), 2);
    assert.equal(await nav.getByRole('button').count(), 1);
    assert.equal(await nav.locator('a[href="/admin/books"]').count(), 0);
  });
  assert.deepEqual(errors, []);
  mkdirSync(fileURLToPath(new URL('../test-artifacts/', import.meta.url)), { recursive: true });
  await page.screenshot({ path: fileURLToPath(new URL('../test-artifacts/admin-grouped-navigation.png', import.meta.url)), fullPage: true });
});

import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createServer } from 'vite';
import { initialWorkflowPolicy } from '../../backend/src/modules/franchise/policy.js';

const chrome = process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
test('direct franchise wizard preserves guest input and authenticated submission contract (mocked HTTP)', { skip: !existsSync(chrome), timeout: 180000 }, async t => {
  const vite = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { host: '127.0.0.1', port: 0, hmr: false, watch: null }, logLevel: 'error' });
  await vite.listen();
  const browser = await chromium.launch({ executablePath: chrome, headless: true });
  t.after(async () => { await browser.close(); await vite.close(); });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } }); page.setDefaultTimeout(20000);
  const base = 'http://127.0.0.1:' + vite.httpServer.address().port;
  let user = null, published = true, row, ownReads = 0, delayedSave;
  const policy = { ...initialWorkflowPolicy(), documents: [] }, writes = [], errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', async route => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname.replace('/api/v1', '');
    if (url.origin !== base) return route.abort();
    if (!url.pathname.startsWith('/api/')) return route.continue();
    let data = [];
    if (path === '/auth/me') data = { user };
    else if (path === '/public/franchise-policy') data = published ? { policy } : { message: 'Applications are not open yet.' };
    else if (path === '/public/payment-config') data = { available: false };
    else if (path === '/public/settings') data = {};
    else if (path === '/auth/csrf') data = { csrfToken: 'synthetic-csrf' };
    else if (path === '/me/franchise-applications') { ownReads++; data = []; }
    else if (path.startsWith('/franchise-applications') && request.method() !== 'GET') {
      assert.ok(user?.emailVerified);
      const body = request.postDataJSON(); writes.push({ path, body });
      row = { ...row, ...body, id: 'application-1', reference: 'FR-TEST', workflowVersion: 1, revision: (row?.revision || 0) + 1, policySnapshot: policy, status: path.endsWith('/submit') ? 'pending' : 'draft', affiliationState: 'inactive' };
      data = row;
      if (delayedSave) await delayedSave;
    } else if (path.endsWith('/status')) data = row;
    await route.fulfill({ json: { data, meta: { total: 0, page: 1, totalPages: 1 } } });
  });
  const step = name => page.getByRole('navigation', { name: 'Franchise registration steps' }).getByRole('button', { name: new RegExp(name) });
  await page.goto(base + '/register', { waitUntil: 'domcontentloaded', timeout: 120000 });
  await page.getByRole('button', { name: 'Apply for Franchise', exact: true }).click();
  await page.getByRole('heading', { name: 'Franchise Registration', exact: true }).waitFor();
  assert.equal(await page.getByRole('navigation', { name: 'Franchise registration steps' }).getByRole('button').count(), 5);
  await page.setViewportSize({width:1366,height:768});await page.screenshot({path:fileURLToPath(new URL('../../.runtime/original-franchise.png',import.meta.url)),fullPage:true});await page.setViewportSize({width:390,height:844});
  await page.getByRole('button', { name: 'Next step', exact: true }).click();
  assert.equal(await step('Institution').getAttribute('aria-current'), 'step');
  await page.getByLabel('Institution name', { exact: true }).fill('Visitor Institute');
  await page.getByLabel('Institution type', { exact: true }).selectOption('Institute');
  await page.getByRole('button', { name: 'Next step', exact: true }).click();
  await page.getByLabel('Apply for an existing university and college').check();
  assert.equal(await page.getByRole('button', { name: 'Next step', exact: true }).isDisabled(),true);
  assert.equal(await step('Affiliation').getAttribute('aria-current'), 'step');
  await page.getByLabel('Apply for an existing university and college').uncheck();
  await page.getByRole('button', { name: 'Next step', exact: true }).click();
  for (const [label, value] of [['Contact person', 'Applicant'], ['Contact email', 'applicant@example.invalid'], ['Contact mobile', '9999999999']]) await page.getByLabel(label, { exact: true }).fill(value);
  await page.getByRole('button', { name: 'Next step', exact: true }).click();
  for (const [label, value] of [['Address', 'Test street'], ['City', 'Test City'], ['Pincode', '123456']]) await page.getByLabel(label, { exact: true }).fill(value);
  await page.getByRole('button', { name: 'Next step', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Save application draft', exact: true }).isDisabled(), true);
  assert.equal(ownReads, 0); assert.equal(writes.length, 0);
  await page.getByRole('region', { name: 'Registration account' }).waitFor();
  user = { id: 'applicant-1', emailVerified: false, permissions: [] };
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByText('Verify your account to continue', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Save application draft', exact: true }).isDisabled(), true);
  user.emailVerified = true;
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Save application draft')?.disabled);
  await page.getByRole('button', { name: 'Save application draft', exact: true }).click();
  await page.getByText('Draft saved. Attach the required documents before submitting.', { exact: true }).waitFor();
  assert.equal(writes[0].body.institution.name, 'Visitor Institute');
  assert.equal(writes[0].body.contact.email, 'applicant@example.invalid');
  await page.getByRole('checkbox', { name: 'Accept franchise agreement', exact: true }).check();
  await page.getByRole('button', { name: 'Submit franchise application', exact: true }).click();
  await page.getByText('Application submitted. KITSS staff will review your details and documents.', { exact: true }).waitFor();
  assert.deepEqual(writes.at(-1).body, { expectedRevision: 2, declaration: { version: policy.agreement.version, accepted: true } });
  user = { id: 'different-account', emailVerified: true, permissions: [] };
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByLabel('Institution name', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Institution name', { exact: true }).inputValue(), '');
  published = false; user = null;
  await page.goto(base + '/register?type=franchise');
  await page.getByText('Applications are not open yet.', { exact: true }).waitFor();
  await page.getByLabel('Institution name', { exact: true }).fill('Can still start');
  await step('Documents').click();
  assert.equal(await page.getByRole('button', { name: 'Save application draft', exact: true }).isDisabled(), true);
  assert.equal(await page.getByText('Joining: Free', { exact: false }).count(), 0);
  for (const width of [390, 320]) { await page.setViewportSize({ width, height: 844 }); assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)); }
  published = true; user = { id: 'applicant-1', emailVerified: true, permissions: [] }; row = undefined;
  await page.goto(base + '/register?type=franchise');
  await page.getByLabel('Institution name', { exact: true }).fill('Private unsaved institute');
  await step('Documents').click();
  let releaseSave;
  delayedSave = new Promise(resolve => { releaseSave = resolve; });
  const issued = page.waitForRequest(r => r.method() === 'POST' && new URL(r.url()).pathname === '/api/v1/franchise-applications');
  await page.getByRole('button', { name: 'Save application draft', exact: true }).click(); await issued;
  user = { id: 'new-owner', emailVerified: true, permissions: [] };
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByLabel('Institution name', { exact: true }).waitFor();
  const completed = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/franchise-applications');
  releaseSave(); await completed;
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await page.getByLabel('Institution name', { exact: true }).inputValue(), '');
  assert.equal(await page.getByText('Reference: FR-TEST', { exact: true }).count(), 0);
  assert.equal(await page.getByText('Draft saved. Attach the required documents before submitting.', { exact: true }).count(), 0);
  // Saving allows an incomplete draft but not a badly formatted value; submitting jumps to the first incomplete step.
  const before = writes.length;
  await page.getByLabel('Institution name', { exact: true }).fill('Partial Institute');
  await step('Contact').click(); await page.getByLabel('Contact email', { exact: true }).fill('not-an-email');
  await step('Documents').click(); await page.getByRole('button', { name: 'Save application draft', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: /^Check the Contact step:/ }).waitFor();
  assert.equal(await step('Contact').getAttribute('aria-current'), 'step'); assert.equal(writes.length, before);
  await page.getByLabel('Contact email', { exact: true }).fill('partial@example.invalid');
  await step('Documents').click(); await page.getByRole('button', { name: 'Save application draft', exact: true }).click();
  await page.getByText('Draft saved. Attach the required documents before submitting.', { exact: true }).waitFor();
  const saved = writes.length;
  await page.getByRole('checkbox', { name: 'Accept franchise agreement', exact: true }).check();
  await page.getByRole('button', { name: 'Submit franchise application', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: /^Check the Institution step:/ }).waitFor();
  assert.equal(await step('Institution').getAttribute('aria-current'), 'step'); assert.equal(writes.length, saved);
  await page.getByRole('button', { name: 'Back to registration options', exact: true }).click();
  assert.equal(new URL(page.url()).searchParams.has('draft'), false);
  for (const [button, heading, type] of [['Coaching Registration', 'Student Tuition / Coaching Admission Form', 'tuition'], ['Student Registration', 'Study Registration Form', 'study'], ['Apply as Educator', 'Teacher / Professor Registration Form', 'teacher']]) {
    await page.getByRole('button', { name: button, exact: true }).click();
    await page.getByRole('heading', { name: heading, exact: true }).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('type'), type);
    assert.equal(await page.getByRole('region',{name:'Registration account'}).isVisible(),false);
    await page.setViewportSize({width:1366,height:768});
    await page.screenshot({path:fileURLToPath(new URL('../../.runtime/original-'+type+'.png',import.meta.url)),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button', { name: 'Back to registration options', exact: true }).click();
    await page.getByRole('heading', { name: 'Select Your Registration Form', exact: true }).waitFor();
  }
  assert.deepEqual(errors, []);
});

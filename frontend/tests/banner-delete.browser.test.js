import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { Readable } from 'node:stream';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createServer } from 'vite';
import { publishingFixture, fakeCleanScanner, imageBytes } from '../../backend/tests/publishing-fixture.js';

const database = process.env.KITSS_BANNER_DELETE_TEST_DB;
test('banner delete: protected API, confirmation and durable public/admin removal', { skip: !database ? 'No fresh isolated banner test database' : false, timeout: 300000 }, async t => {
  const f = await publishingFixture(database, { scanner: fakeCleanScanner });
  let server, vite, browser;
  t.after(async () => { await browser?.close(); await vite?.close(); if (server) await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); await f.close(); });
  const admin = await f.fixtureUser(), reader = await f.fixtureUser(['admin'], ['content.read']);
  const image = await f.media.upload({ purpose: 'banner', stream: Readable.from(await imageBytes()), mime: 'image/png', originalName: 'synthetic-banner.png', idempotencyKey: randomUUID(), auth: admin.auth, ctx: f.ctx });
  const create = title => f.publishing.create('banners', { title, placement: 'home', imageAssetId: image.id, link: { type: 'internal', target: '/books' } }, admin.auth, f.ctx);
  const draft = await create('DELETE TEST DRAFT');
  let published = await create('DELETE TEST PUBLISHED');
  published = await f.publishing.publish('banners', published.id, { publish: true, expectedRevision: published.revision }, admin.auth, f.ctx);
  server = http.createServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  vite = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { host: '127.0.0.1', port: 0, hmr: false, watch: null, proxy: { '/api': { target: 'http://127.0.0.1:' + server.address().port, changeOrigin: true } } }, logLevel: 'error' });
  await vite.listen(); const base = 'http://127.0.0.1:' + vite.httpServer.address().port;
  f.config.corsOrigins = [base]; f.config.appPublicUrl = base; server.on('request', f.app());
  const csrfResponse = await fetch(base + '/api/v1/auth/csrf');
  const csrfCookie = csrfResponse.headers.getSetCookie()[0].split(';')[0], csrf = (await csrfResponse.json()).data.csrfToken;
  const remove = (row, actor = admin, input = { expectedRevision: row.revision, remove: true }, useCsrf = true) => fetch(base + '/api/v1/admin/content/banners/' + row.id, { method: 'DELETE', headers: { Origin: base, Cookie: [useCsrf ? csrfCookie : '', actor ? 'kitss_staff_session=' + actor.token : ''].filter(Boolean).join('; '), ...(useCsrf ? { 'X-CSRF-Token': csrf } : {}), 'Content-Type': 'application/json' }, body: JSON.stringify(input) });
  await t.test('authorization, CSRF, removal type and revision checks reject invalid deletion', async () => {
    assert.equal((await remove(draft, null)).status, 401);
    assert.equal((await remove(draft, reader)).status, 403);
    assert.equal((await remove(draft, admin, undefined, false)).status, 403);
    assert.equal((await remove(draft, admin, { expectedRevision: draft.revision, remove: 'true' })).status, 422);
    assert.equal((await remove(draft, admin, { expectedRevision: draft.revision + 1, remove: true })).status, 409);
    assert.equal((await f.models.Banner.findById(draft.id)).deletedAt, undefined);
  });
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await context.addCookies([{ name: 'kitss_staff_session', value: admin.token, url: base, httpOnly: true, sameSite: 'Lax' }]);
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  const page = await context.newPage(); page.setDefaultTimeout(30000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await t.test('cancel/Escape preserve the banner; keyboard confirm removes a published banner', async () => {
    await page.goto(base + '/admin/content', { waitUntil: 'domcontentloaded', timeout: 120000 });
    await page.getByRole('button', { name: 'Banners', exact: true }).click();
    const row = page.getByRole('row').filter({ hasText: published.title }); await row.waitFor();
    await row.getByRole('button', { name: 'Delete', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Delete banner?', exact: true }); await dialog.waitFor();
    assert.ok(await dialog.evaluate(node => node.contains(document.activeElement)));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
    assert.equal((await f.models.Banner.findById(published.id)).status, 'published');
    await row.getByRole('button', { name: 'Delete', exact: true }).click();
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click(); await row.waitFor();
    await row.getByRole('button', { name: 'Delete', exact: true }).click();
    await dialog.getByRole('button', { name: 'Delete banner', exact: true }).focus(); await page.keyboard.press('Enter');
    await dialog.waitFor({ state: 'detached' }); await row.waitFor({ state: 'detached' });
    const stored = await f.models.Banner.findById(published.id);
    assert.ok(stored.deletedAt); assert.equal(stored.publishedSnapshot, null);
    assert.ok(await f.models.MediaAsset.findById(image.id));
    assert.equal((await f.publishing.list('banners', { placement: 'home' })).data.some(row => row.id === published.id), false);
    assert.equal((await (await fetch(base + '/api/v1/public/banners?placement=home')).json()).data.some(row => row.id === published.id), false);
    assert.equal((await f.publishing.list('banners', {}, true)).meta.total, 1);
    await assert.rejects(f.publishing.publish('banners', published.id, { publish: true, expectedRevision: stored.revision }, admin.auth, f.ctx), error => error.status === 404);
    assert.equal((await remove(published)).status, 404);
    assert.equal(await f.models.AuditLog.countDocuments({ action: 'banners_deleted', subjectId: published.id }), 1);
  });
  await t.test('archive stays distinct; archived banner can subsequently be deleted', async () => {
    const response = await remove(draft, admin, { expectedRevision: draft.revision }); assert.equal(response.status, 200);
    const archived = (await response.json()).data;
    assert.equal((await f.publishing.list('banners', { status: 'archived' }, true)).data.length, 1);
    assert.equal((await remove(archived)).status, 200);
    assert.equal((await f.publishing.list('banners', {}, true)).meta.total, 0);
    const other = await f.publishing.create('pages', { key: 'home', sections: [] }, admin.auth, f.ctx);
    await assert.rejects(f.publishing.archive('pages', other.id, { expectedRevision: other.revision, remove: true }, f.ctx), error => error.status === 422);
  });
  assert.deepEqual(errors, []);
});
